#ifndef CLEM_NUMERICS_CONFIG_H
#define CLEM_NUMERICS_CONFIG_H

namespace clem {

    /**
     * Available thermal diffusion schemes for the LEM periodic ring.
     *
     * All schemes use CFL-based sub-stepping and are unconditionally stable for
     * any LES timestep dt.  The difference is the spatial stencil accuracy and
     * the time integrator used within each sub-step.
     *
     *  O2_Euler   : 2nd-order central difference, explicit Euler sub-steps.
     *               Sub-step CFL: r = alpha*dt_sub/dm^2 <= 0.5.
     *
     *  O4_Euler   : 4th-order conservative face-flux stencil, explicit Euler sub-steps.
     *               Sub-step CFL: r <= 3/11 ~ 0.27 (stricter than O2, more sub-steps).
     *
     *  O2_RK2     : 2nd-order space, Heun's predictor-corrector sub-steps.
     *               Sub-step CFL: r <= 0.5. 2nd-order accurate in time per sub-step.
     *
     *  O2_Substep : Alias of O2_Euler (kept for backward compatibility).
     *
     * To select a scheme, edit clem_setup.H — do not edit this file.
     */
    enum class DiffusionScheme {
        O2_Euler   = 0,
        O4_Euler   = 1,
        O2_RK2     = 2,
        O2_Substep = 3
    };

} // namespace clem

#endif /* CLEM_NUMERICS_CONFIG_H */
